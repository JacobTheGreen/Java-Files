import java.util.Scanner;

public class NumberPatternJRB{   //header of the class
   public static void main(  String[] args ){
      for (int i = 1; i < 7; System.out.print( i++ + " " ));//prints 1 2 3 4 5 6
      System.out.println("");
      for (int i = 1; i < 6; System.out.print( i++ + " " ));//prints 1 2 3 4 5
      System.out.println("");
      for (int i = 1; i < 5; System.out.print( i++ + " " ));//prints 1 2 3 4
      System.out.println("");
      for (int i = 1; i < 4; System.out.print( i++ + " " ));//prints 1 2 3
      System.out.println("");
      for (int i = 1; i < 3; System.out.print( i++ + " " ));//prints 1 2
      System.out.println("");
      for (int i = 1; i < 2; System.out.print( i++ + " " ));//prints 1
      
      
      
      
      
            
   }//end of main


}//end of class